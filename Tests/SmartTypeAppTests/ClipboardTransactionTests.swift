import AppKit
import Testing

@testable import SmartTypeApp

@Suite struct ClipboardTransactionTests {
    @Test func theSelectionIsCopiedAndItsTextReturned() async {
        let app = FakeFrontApp()
        app.selection = "ghbdtn"
        let clipboard = app.clipboard()

        let copied = await clipboard.run { await clipboard.copySelection() } ?? nil

        #expect(copied == "ghbdtn")
    }

    /// No change to the pasteboard means nothing was selected: what was there before is never
    /// taken for the selection.
    @Test func withNothingSelectedNothingIsCopied() async {
        let app = FakeFrontApp()
        app.pasteboard.setString("yesterday's clipboard", forType: .string)
        let clipboard = app.clipboard()

        let copied = await clipboard.run { await clipboard.copySelection() } ?? nil

        #expect(app.copies == 1)
        #expect(copied == nil)
    }

    /// A picture is not text, yet ⌘C still replaced the clipboard, so it is still given back.
    @Test func aSelectedImageIsNotTextButTheClipboardComesBack() async {
        let app = FakeFrontApp()
        app.pasteboard.setString("the person's clipboard", forType: .string)
        app.selectsAnImage = true
        let clipboard = app.clipboard()

        let copied = await clipboard.run { await clipboard.copySelection() } ?? nil

        #expect(copied == nil)
        #expect(app.pasteboard.string(forType: .string) == "the person's clipboard")
    }

    @Test func thePersonsClipboardIsGivenBackAfterThePaste() async {
        let app = FakeFrontApp()
        app.pasteboard.setString("the person's clipboard", forType: .string)
        app.selection = "ghbdtn"
        let clipboard = app.clipboard()

        await clipboard.run {
            _ = await clipboard.copySelection()
            await clipboard.paste("привет")
        }

        #expect(app.pasted == ["привет"])
        #expect(app.pasteboard.string(forType: .string) == "the person's clipboard")
    }

    /// Whoever writes to the pasteboard while SmartType borrows it keeps what they wrote.
    @Test func somethingCopiedMeanwhileIsKept() async {
        let app = FakeFrontApp()
        app.pasteboard.setString("the person's clipboard", forType: .string)
        app.selection = "ghbdtn"
        let clipboard = app.clipboard()

        await clipboard.run {
            _ = await clipboard.copySelection()
            await clipboard.paste("привет")
            app.pasteboard.clearContents()
            app.pasteboard.setString("copied meanwhile", forType: .string)
        }

        #expect(app.pasteboard.string(forType: .string) == "copied meanwhile")
    }

    @Test func thePastedTextIsMarkedSoClipboardManagersSkipIt() async {
        let app = FakeFrontApp()
        let clipboard = app.clipboard()

        await clipboard.run { await clipboard.paste("привет") }

        let types = app.typesAtPaste.first ?? []
        #expect(types.contains(.init("org.nspasteboard.TransientType")))
        #expect(types.contains(.init("org.nspasteboard.AutoGeneratedType")))
    }

    @Test func aPasteboardNothingChangedIsNotWrittenAgain() async {
        let app = FakeFrontApp()
        app.pasteboard.setString("the person's clipboard", forType: .string)
        let before = app.pasteboard.changeCount
        let clipboard = app.clipboard()

        await clipboard.run { _ = await clipboard.copySelection() }

        #expect(app.pasteboard.changeCount == before)
    }

    /// Paste from Other Apps set to Deny: ⌘C would overwrite a clipboard SmartType could not
    /// put back, so nothing is pressed at all.
    @Test func aPasteboardSmartTypeMayNotReadIsNotBorrowed() async {
        let app = FakeFrontApp()
        app.selection = "ghbdtn"
        let clipboard = app.clipboard(isDenied: true)

        let borrowed: Void? = await clipboard.run { _ = await clipboard.copySelection() }

        #expect(borrowed == nil)
        #expect(app.copies == 0)
    }
}
